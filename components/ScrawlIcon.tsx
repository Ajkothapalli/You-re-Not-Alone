// ─── Build lookup maps ─────────────────────────────────────────────────────────

const ICON_PATHS: Record<string, string[]> = Object.fromEntries(ICON_DEFS);
export const ALL_ICON_NAMES: string[] = ICON_DEFS.map(([name]) => name);

export type ScrawlIconName = string;

// djb2 hash over all characters — avoids collisions from seeds sharing a last character.
function seedHash(s: string): number {
  let h = 5381;
  for (let i = 0; i < s.length; i++) {
    h = (((h << 5) + h) + s.charCodeAt(i)) >>> 0;
  }
  return h;
}

// sessionOffset shifts all icons when the user returns to the screen.
// offset=0/2/4 gives 3 different icons per card (never collide within 102-icon pool).
export function iconAtOffset(seed: string, offset: number, sessionOffset = 0): ScrawlIconName {
  const n = ALL_ICON_NAMES.length;
  return ALL_ICON_NAMES[(seedHash(seed) + offset + sessionOffset) % n];
}

// kept for backward compat — same as iconAtOffset(seed, 0)
export function iconFromSeed(seed: string): ScrawlIconName {
  return iconAtOffset(seed, 0);
}

// ─── Component ────────────────────────────────────────────────────────────────

const FILTER_ID = 'scrawl_roughen';

interface Props {
  name:        ScrawlIconName;
  size?:       number;
  color?:      string;
  roughen?:    boolean;
  strokeWidth?: number;
}

export function ScrawlIcon({ name, size = 48, color = '#F5F5F5', roughen = true, strokeWidth = 2.5 }: Props) {
  const paths = ICON_PATHS[name] ?? ICON_PATHS['heart'];

  return (
    <Svg viewBox="0 0 48 48" width={size} height={size}>
      {roughen && (
        <Defs>
          <Filter id={FILTER_ID} x="-10%" y="-10%" width="120%" height="120%">
            <FeTurbulence
              type="fractalNoise"
              baseFrequency="0.038"
              numOctaves={2}
              seed={5}
              result="noise"
            />
            <FeDisplacementMap
              in="SourceGraphic"
              in2="noise"
              scale={2.6}
              xChannelSelector="R"
              yChannelSelector="G"
            />
          </Filter>
        </Defs>
      )}
      <G
        stroke={color}
        strokeWidth={strokeWidth}
        strokeLinejoin="round"
        strokeLinecap="round"
        fill="none"
        filter={roughen ? `url(#${FILTER_ID})` : undefined}
      >
        {paths.map((d, i) => (
          <Path key={i} d={d} />
        ))}
      </G>
    </Svg>
  );
}
